"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const root=path.resolve(__dirname,"..");
const load=p=>JSON.parse(fs.readFileSync(path.join(root,p),"utf8"));
const C=require("../core/contracts/contract-v1.js");
const vars=load("core/contracts/variables.v1.json");
const registry=load("core/contracts/models.v1.json");
const example=load("core/contracts/scenario.example.v1.json");
assert.equal(new Set(vars.variables.map(v=>v.id)).size,vars.variables.length,"variable IDs unique");
assert.equal(new Set(registry.models.map(v=>v.id)).size,registry.models.length,"model IDs unique");
assert.equal(C.validateScenario(example,vars).ok,true,JSON.stringify(C.validateScenario(example,vars).errors));
const copy=x=>JSON.parse(JSON.stringify(x));
let s=copy(example);s.changes[0].unit="亿元";assert(C.validateScenario(s,vars).errors.some(x=>x.code==="UNIT_MISMATCH"));
s=copy(example);s.changes[0].variable="firm.cash_runway";s.changes[0].unit="月";s.changes[0].kind="state";
assert(C.validateScenario(s,vars).errors.some(x=>x.code==="NOT_IMPLEMENTED"));
s=copy(example);s.evidence_mode="verified";
assert(C.validateScenario(s,vars).errors.some(x=>x.code==="REVIEW"));
s=copy(example);s.period.start="2033-Q1";
assert(C.validateScenario(s,vars).errors.some(x=>x.code==="PERIOD_ORDER"));
s=copy(example);s.changes.push({variable:"macro.gdp",kind:"state",unit:"亿元",value:1000});
assert(C.validateScenario(s,vars).errors.some(x=>x.code==="KIND_MISMATCH"));
assert.equal(C.modelCheck("internal.career_v12",registry).ready,false);
const a={model_id:"legacy.gdp2030",model_version:"1",measure:"regional_value_added",unit:"亿元",period:"2030",data_snapshot:"demo"};
const b={...a,model_id:"internal.career_v12",model_version:"12"};
assert.equal(C.compareOutputs(a,b,registry).code,"INCOMPATIBLE_MODELS");
assert.equal(C.compareOutputs(a,{...a,unit:"%"},registry).code,"DIMENSION_MISMATCH");
assert.equal(C.compareOutputs(a,{...a},registry).ok,true);
assert.equal(C.compareOutputs(a,{...a,model_version:"2"},registry).code,"VERSION_MISMATCH");
const envelope=C.envelope(example,registry.models[0],{p50:1},{measure:"value_added_share",unit:"比例",period:"2032"});
assert.equal(envelope.status,"unverified");
assert.equal(envelope.result.p50,1);
console.log("PASS contracts-v1: variable IDs, scenario shape, evidence gates, unit guards, model comparability and envelopes");
