'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {chromium}=require('playwright');
(async()=>{
 fs.mkdirSync('artifacts',{recursive:true});
 const browser=await chromium.launch({headless:true});
 const errors=[];
 const page=await browser.newPage({viewport:{width:1440,height:950},deviceScaleFactor:1});
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error'&&!/favicon/i.test(m.text()))errors.push(m.text())});
 try{
  await page.goto('http://127.0.0.1:8765/v11/internal/league.html',{waitUntil:'networkidle'});
  await page.waitForSelector('#blcToggle');
  assert.equal(await page.locator('#blcDrawer.open').count(),0);
  await page.locator('#blcToggle').click();
  assert.equal(await page.locator('#blcDrawer.open').count(),1,'coach opens over existing workspace');
  assert.ok((await page.locator('#blcContext').innerText()).includes('2家阵容主体'));
  assert.ok(await page.locator('#blcBody svg').count()>=1,'network diagnostic map');
  await page.locator('#blcTabs [data-blc-tab="change"]').click();
  assert.equal(await page.locator('#blcBody .blc-sensrow').count(),5,'five scenario sensitivity factors');
  assert.equal(await page.locator('#blcBody .blc-step').count(),8,'synthetic-estimated path coefficients');
  assert.ok((await page.locator('#blcBody').innerText()).includes('重复抽样'));
  await page.locator('#blcTabs [data-blc-tab="future"]').click();
  assert.equal(await page.locator('#blcBody .blc-kpi').count(),6,'distribution and paired comparison');
  assert.ok((await page.locator('#blcBody').innerText()).includes('P90'));
  await page.locator('#blcVol').selectOption('hard');
  assert.ok(await page.locator('#blcBody svg').count()>=1,'future uncertainty band');
  await page.screenshot({path:'artifacts/boluo-v11-coach-desktop.png',fullPage:false});
  await page.locator('#blcClose').click();
  await page.locator('#nav button[data-view="tactics"]').click();
  await page.locator('#mgrPresetFuture').click();
  assert.equal(await page.locator('#mgrRoles .mgr-slot.filled').count(),3,'future lineup contains three selected candidates');
  await page.locator('#blcToggle').click();
  assert.ok((await page.locator('#blcContext').innerText()).includes('3家阵容主体'),'coach adopts lineup');
  await page.locator('#blcClose').click();
  await page.locator('#nav button[data-view="season"]').click();
  await page.locator('#v9FourQuarters').click();
  assert.equal(await page.locator('#careerClock').innerText(),'2026 Q4','quarter clock advances');
  await page.locator('#v10Run').click();
  assert.equal(await page.locator('#v10Results .v10-result').count(),3,'three 28-quarter competition routes');
  await page.locator('#blcToggle').click();
  assert.ok((await page.locator('#blcContext').innerText()).includes('2026 Q4'),'coach uses current season quarter');
  await page.locator('#blcClose').click();
  await page.setViewportSize({width:390,height:844});
  await page.locator('#blcToggle').click();
  const rect=await page.locator('#blcDrawer').boundingBox();
  assert.ok(rect&&rect.width>=380&&rect.width<=400,'coach drawer is mobile-width');
  await page.locator('#blcTabs [data-blc-tab="future"]').click();
  await page.screenshot({path:'artifacts/boluo-v11-coach-mobile.png',fullPage:false});
  assert.deepEqual(errors,[],'no console or runtime errors during desktop/mobile workflow');
  console.log('PASS: Boluo coach browser interactions, cross-view state, V10 seasons, mobile view');
 }finally{await browser.close()}
})().catch(err=>{console.error(err);process.exit(1)});
