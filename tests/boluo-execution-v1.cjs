"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm"),path=require("node:path");
const root=path.join(__dirname,"..");
const file=p=>fs.readFileSync(path.join(root,p),"utf8");
const json=p=>JSON.parse(file(p));
const ctx={window:{}};vm.createContext(ctx);
for(const p of ["lab-2032/core.js","lab-2032/engine.js"])vm.runInContext(file(p),ctx,{filename:p});
const Bridge=require("../core/adapters/lab2032-project-v1.js");
const Contracts=require("../core/contracts/contract-v1.js");
const dictionary=json("core/contracts/variables.v1.json"),registry=json("core/contracts/models.v1.json"),scenario=json("core/contracts/scenario.example.v1.json");
const runtime={Core:ctx.window.BoluoCore,Engine:ctx.window.BoluoEngine,Contracts};
const a=Bridge.run(scenario,dictionary,registry,runtime,{draws:500,affectedPct:50,proxyStrength:.5});
const b=Bridge.run(scenario,dictionary,registry,runtime,{draws:500,affectedPct:50,proxyStrength:.5});
assert.equal(JSON.stringify(a),JSON.stringify(b),"identical seed, params and dataset yield same result");
assert(a.projects.delayed>0,"must actually shift projects");
assert.equal(a.projects.delayed,a.projects.selected);
assert(a.projects.after2032<=a.projects.before2032);
assert(a.baseline.gdp.p10<=a.baseline.gdp.p50&&a.baseline.gdp.p50<=a.baseline.gdp.p90);
assert(a.illustrativeMacroStress.gdp.p10<=a.illustrativeMacroStress.gdp.p50);
assert.equal(a.mapping.causal_link_established,false);
const demo=runtime.Core.demo(),before=runtime.Core.identity(demo);
Bridge.run(scenario,dictionary,registry,runtime,{data:demo});
assert.equal(runtime.Core.identity(demo),before,"no mutation of source data");
const unchanged=Bridge.run({...scenario,changes:scenario.changes.map(c=>c.variable==="project.delay_years"?{...c,value:0}:c)},dictionary,registry,runtime);
assert.equal(unchanged.macroDifference,0,"zero delay produces equal paired macro draws");
assert.equal(unchanged.projects.delayed,0);
assert.throws(()=>Bridge.run({...scenario,evidence_mode:"verified",review_id:"yes"},dictionary,registry,runtime),/rejects mixed/);
assert.throws(()=>Bridge.run(scenario,dictionary,registry,runtime,{proxyStrength:2}),/Proxy strength/);
console.log("PASS: original BoluoEngine.simulate paired, deterministic, project schedule shifted, zero case, no mutation, safety boundaries");
console.log(JSON.stringify({projects:a.projects.delayed,crossed2032:a.projects.crossed2032,baselineP50:a.baseline.gdp.p50,assumedStressP50:a.illustrativeMacroStress.gdp.p50}).slice(0,600));
