'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {chromium}=require('playwright');
(async()=>{
 fs.mkdirSync('artifacts',{recursive:true});
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error'&&!/favicon/i.test(m.text()))errors.push(m.text())});
 await page.goto('http://127.0.0.1:8765/v11/impact.html',{waitUntil:'networkidle'});
 await page.waitForSelector('#factNetwork .signal-node');
 assert.equal(await page.locator('.v11-nav-groups a[href="./holo.html"]').count(),1,'02 is holographic network');
 assert.equal(await page.locator('.v11-nav-groups a[href="./base-target.html"]').count(),1,'03 is fundamentals');
 assert.equal(await page.locator('.v11-nav-groups a[href="./industry-chain.html"]').count(),1,'04 is structure benchmark');
 assert.equal(await page.locator('.v11-nav-groups a[href="./impact.html"][aria-current="page"]').count(),1,'05 is change impact');
 assert.equal(await page.locator('.impact-bridge a[href="./industry-chain.html"]').count(),1,'04 to 05 bridge');
 assert.equal(await page.locator('.impact-bridge a[href="./plan.html"]').count(),1,'05 to 06 bridge');
 assert.equal(await page.locator('.fact-tile').count(),4,'four sourced 2026 Q3 signals');
 assert.equal(await page.locator('#factNetwork .signal-node').count(),4,'four factual indicators');
 assert.equal(await page.locator('#scenarioNetwork .signal-node').count(),5,'five transmission nodes');
 assert.equal(await page.locator('.stage-duo .graph-panel').count(),2,'dual network stage');
 await page.locator('[data-case="orders"]').click();
 assert.match(await page.locator('#stageTitle').innerText(),/本地订单/,'orders scenario');
 assert.match(await page.locator('#chainMiddle').innerText(),/采购订单/,'orders path');
 await page.locator('#impactStep').evaluate(el=>{el.value='3';el.dispatchEvent(new Event('input',{bubbles:true}))});
 assert.equal(await page.locator('#stepOutput').innerText(),'3 / 4','slider advances');
 assert.equal(await page.locator('#scenarioNetwork .flow-link.active').count(),3,'active links match step');
 await page.locator('[data-mode="trace"]').click();
 assert.equal(await page.locator('#stageDuo.focus-mode').count(),1,'trace expands graph');
 await page.locator('[data-lens="people"]').click();
 assert.match(await page.locator('#inspectorQuestion').innerText(),/招聘和工资/,'people lens');
 await page.locator('[data-case="projects"]').click();
 await page.locator('#playShock').click();
 await page.waitForTimeout(1550);
 assert.ok(Number((await page.locator('#stepOutput').innerText()).split(' ')[0])>=1,'play shock advances');
 await page.locator('#resetShock').click();
 assert.equal(await page.locator('#stepOutput').innerText(),'0 / 4','reset graph');
 await page.locator('#openEvidence').click();
 assert.equal(await page.locator('#detailDialog').evaluate(el=>el.open),true,'source dialog opens');
 await page.locator('#dialogClose').click();
 await page.screenshot({path:'artifacts/impact-premium-desktop.png',fullPage:true});
 assert.deepEqual(errors,[],'desktop has no JS errors');
 await page.setViewportSize({width:390,height:844});
 await page.reload({waitUntil:'networkidle'});
 await page.waitForSelector('#scenarioNetwork .signal-node');
 assert.equal(await page.locator('.mobile-nav a').count(),5,'mobile navigation has five items');
 assert.equal(await page.locator('.mobile-nav a[aria-current="page"]').count(),1,'mobile active 05');
 assert.equal(await page.locator('#scenarioNetwork .signal-node').count(),5,'mobile graph');
 await page.locator('[data-case="livelihood"]').click();
 assert.match(await page.locator('#stageTitle').innerText(),/就业消费/,'mobile scenario');
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth);
 assert.ok(overflow<=2,'mobile horizontal overflow '+overflow+'px');
 await page.screenshot({path:'artifacts/impact-premium-mobile.png',fullPage:true});
 assert.deepEqual(errors,[],'mobile has no JS errors');
 await browser.close();
 process.stdout.write('PASS: V11 05 navigation, factual inputs, scenarios, graph playback, lenses and responsive layout.\n');
})().catch(e=>{console.error(e);process.exit(1)});
